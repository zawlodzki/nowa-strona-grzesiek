#!/usr/bin/env node
// Compiles migration/contracts/tokens.json (DTCG) into tokens.css.
// Usage: node build-tokens.mjs [--check]   (--check fails when tokens.css is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const SOURCE = here('../../../../migration/contracts/tokens.json');
const TARGET = here('./tokens.css');

// Top-level groups whose name is dropped from the property, so
// semantic.text.heading becomes --text-heading.
const FLATTEN = new Set(['semantic']);

const tokens = JSON.parse(readFileSync(SOURCE, 'utf8'));

function propName(path) {
  const parts = FLATTEN.has(path[0]) ? path.slice(1) : path;
  return `--${parts.join('-')}`;
}

function srgbToLinear(c) {
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

function linearToSrgb(c) {
  return c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;
}

function hexToOklch(hex) {
  const m = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(hex);
  if (!m) throw new Error(`not a #rrggbb[aa] colour: ${hex}`);
  const [r, g, b] = [0, 2, 4].map((i) => srgbToLinear(parseInt(m[1].slice(i, i + 2), 16) / 255));
  const alpha = m[2] ? parseInt(m[2], 16) / 255 : 1;
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const mm = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * mm - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * mm + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * mm - 0.808675766 * s;
  const C = Math.hypot(A, B);
  const H = ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360;
  return { L, C, H, alpha };
}

function oklchToHex({ L, C, H }) {
  const A = C * Math.cos((H * Math.PI) / 180);
  const B = C * Math.sin((H * Math.PI) / 180);
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return '#' + rgb.map((c) => Math.round(Math.min(1, Math.max(0, linearToSrgb(c))) * 255).toString(16).padStart(2, '0')).join('');
}

const round = (n, d) => Number(n.toFixed(d));

function color(hex) {
  const { L, C, H, alpha } = hexToOklch(hex);
  const achromatic = C < 1e-4;
  const out = { L: round(L, 5), C: achromatic ? 0 : round(C, 5), H: achromatic ? 0 : round(H, 3) };
  const back = oklchToHex(out);
  if (back !== hex.slice(0, 7).toLowerCase()) throw new Error(`${hex} does not round-trip (got ${back})`);
  const a = alpha < 1 ? ` / ${round(alpha, 3)}` : '';
  return `oklch(${round(out.L * 100, 3)}% ${out.C} ${achromatic ? 'none' : out.H}${a})`;
}

function ref(value) {
  return value.replace(/\{([^}]+)\}/g, (_, p) => `var(${propName(p.split('.'))})`);
}

function maybeColor(v) {
  return /^#[0-9a-f]{6,8}$/i.test(v) ? color(v) : ref(v);
}

function family(list) {
  return list.map((f) => (/^[\w-]+$/.test(f) ? f : `'${f}'`)).join(', ');
}

// One entry per DTCG $type: returns [suffix, css value] pairs.
const EMIT = {
  color: (v) => [['', maybeColor(v)]],
  dimension: (v) => [['', v]],
  duration: (v) => [['', v]],
  string: (v) => [['', v]],
  fontWeight: (v) => [['', String(v)]],
  fontFamily: (v) => [['', family(v)]],
  cubicBezier: (v) => [['', `cubic-bezier(${v.join(', ')})`]],
  shadow: (v) => [['', `${v.offsetX} ${v.offsetY} ${v.blur} ${v.spread} ${maybeColor(v.color)}`]],
  typography: (v) => [
    ['-family', v.fontFamily],
    ['-size', v.fontSize],
    ['-weight', String(v.fontWeight)],
    ['-leading', String(v.lineHeight)],
    ['-tracking', v.letterSpacing],
  ],
};

const lines = [];
function walk(node, path) {
  if ('$value' in node) {
    const emit = EMIT[node.$type];
    if (!emit) throw new Error(`no emitter for $type ${node.$type} at ${path.join('.')}`);
    for (const [suffix, value] of emit(node.$value)) lines.push(`  ${propName(path)}${suffix}: ${value};`);
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    walk(child, [...path, key]);
  }
}
walk(tokens, []);

const css = `/* Generated by build-tokens.mjs from migration/contracts/tokens.json. Do not edit. */
:root {
${lines.join('\n')}
}
`;

if (process.argv.includes('--check')) {
  if (readFileSync(TARGET, 'utf8') !== css) {
    console.error('tokens.css is stale: run node apps/web/src/styles/build-tokens.mjs');
    process.exit(1);
  }
  console.log(`tokens.css up to date (${lines.length} properties)`);
} else {
  writeFileSync(TARGET, css);
  console.log(`wrote ${TARGET} (${lines.length} properties)`);
}
