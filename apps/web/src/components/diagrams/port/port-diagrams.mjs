#!/usr/bin/env node
// Ports the animated diagram embeds from the live Webflow HTML snapshot into
// one Astro component per key, plus registry.ts and Diagram.astro. Rerunning
// it on an unchanged snapshot reproduces the committed files byte for byte.
//
//   node apps/web/src/components/diagrams/port/port-diagrams.mjs [--check]
//
// Reads migration/00-inventory/live-site/html (private inventory) and
// port/sizes.json, which measure-diagrams.mjs writes.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { collect } from './embeds.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = dirname(here);
const repo = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: here, encoding: 'utf8' }).trim();
const htmlDir = join(repo, 'migration/00-inventory/live-site/html');
const sizesPath = join(here, 'sizes.json');
const check = process.argv.includes('--check');

const fail = (msg) => {
  console.error(`port-diagrams: ${msg}`);
  process.exit(1);
};

if (!existsSync(htmlDir)) fail(`missing ${htmlDir}; clone the inventory first (see AGENTS.md)`);

const pascal = (key) => key.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');

function matchBrace(src, open) {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return i;
  }
  fail('unbalanced braces in script');
}

function port({ key, embed, pages }, sizes) {
  const sel = `[data-diagram="${key}"]`;
  const rootAt = embed.indexOf(`<div id="${key}"`);
  const banner = embed.slice(0, rootAt).trim();
  const styleAt = embed.indexOf('<style>');
  let markup = embed.slice(rootAt, styleAt).trim();
  const css = embed.slice(styleAt + 7, embed.indexOf('</style>')).trim();
  let js = embed.slice(embed.indexOf('<script>') + 8, embed.indexOf('</script>')).trim();

  const designW = Number(js.match(/DESIGN_W\s*=\s*(\d+)/)?.[1]);
  if (!designW) fail(`${key}: no DESIGN_W`);
  const size = sizes[key];

  const rootAttrs = `class="dg" data-diagram="${key}" aria-hidden="true" style="--dg-w: ${designW};${size ? ` --dg-h: ${size.h};` : ''}"`;
  markup = markup.replace(`<div id="${key}" aria-hidden="true">`, `<div ${rootAttrs}>`);
  if (!markup.includes(rootAttrs)) fail(`${key}: unexpected root element`);
  let n = 0;
  markup = markup.replace(/<div class="((?:zw|cf)-(stage|fit))">/g, (_, cls, role) => {
    n++;
    return `<div class="${cls} dg-${role}">`;
  });
  if (n !== 2) fail(`${key}: expected one stage and one fit wrapper, found ${n}`);
  markup = markup.replace(/[ \t]*<!--[\s\S]*?-->\n?/g, '');

  const rootDecl = new RegExp(`var root\\s*=\\s*document\\.getElementById\\('${key}'\\);\\s*`);
  if (!rootDecl.test(js)) fail(`${key}: root lookup not found`);
  js = js.replace(rootDecl, '');
  const fitAt = js.indexOf('function fit()');
  if (fitAt < 0) fail(`${key}: no fit()`);
  js = js.slice(0, fitAt) + 'function fit(){}' + js.slice(matchBrace(js, js.indexOf('{', fitAt)) + 1);
  if (js.includes('getElementById')) fail(`${key}: script still looks up ids`);

  const scopedCss = css.split(`#${key}`).join(sel);
  if (/#(?:zw|crm)-/.test(scopedCss.replace(/#[0-9a-fA-F]{3,8}\b/g, ''))) fail(`${key}: css still targets an id`);

  const doc = banner
    .replace(/^<!--\s*=+\s*/, '')
    .replace(/\s*=+\s*-->$/, '')
    .replace(/\n\s*Webflow:[\s\S]*?(?=\n\s*\n|$)/, '')
    .replace(/\*\//g, '* /');
  const front = [
    '---',
    `// Ported from the Webflow embed #${key} (${pages.join(', ')}) by port/port-diagrams.mjs.`,
    "import './diagram.css';",
    ...(doc ? ['/*', ...doc.split('\n').map((l) => `  ${l.trim()}`.trimEnd()), '*/'] : []),
    '---',
  ].join('\n');

  return `${front}

${markup}

<style is:global>
${scopedCss}
</style>

<script>
  // @ts-nocheck
  for (const root of document.querySelectorAll('${sel}')) {
${js}
  }
</script>
`;
}

const sizes = existsSync(sizesPath) ? JSON.parse(readFileSync(sizesPath, 'utf8')) : {};
const diagrams = collect(htmlDir);
const files = new Map();
for (const d of diagrams) files.set(`${pascal(d.key)}.astro`, port(d, sizes));

files.set(
  'registry.ts',
  `// Generated by port/port-diagrams.mjs.
export const diagramPages = {
${diagrams.map((d) => `  '${d.key}': [${d.pages.map((p) => `'${p}'`).join(', ')}],`).join('\n')}
} as const;

export type DiagramKey = keyof typeof diagramPages;

export const diagramKeys = Object.keys(diagramPages) as DiagramKey[];
`,
);

// The key-to-component map lives in an .astro file because plain tsc, which
// CI runs, cannot resolve .astro imports from a .ts module.
files.set(
  'Diagram.astro',
  `---
// Generated by port/port-diagrams.mjs.
import type { DiagramKey } from './registry';
${diagrams.map((d) => `import ${pascal(d.key)} from './${pascal(d.key)}.astro';`).join('\n')}

interface Props {
  diagram: DiagramKey;
}

const diagrams = {
${diagrams.map((d) => `  '${d.key}': ${pascal(d.key)},`).join('\n')}
} satisfies Record<DiagramKey, unknown>;

const Component = diagrams[Astro.props.diagram];
---

<Component />
`,
);

const unsized = diagrams.filter((d) => !sizes[d.key]).map((d) => d.key);
let stale = 0;
for (const [name, body] of files) {
  const path = join(outDir, name);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === body) continue;
  stale++;
  if (check) console.error(`stale: ${name}`);
  else writeFileSync(path, body);
}
console.log(`${diagrams.length} diagrams, ${stale} file(s) ${check ? 'stale' : 'written'}, ${unsized.length} unsized${unsized.length ? `: ${unsized.join(' ')}` : ''}`);
if (check && (stale || unsized.length)) process.exit(1);
